"""Publish reviewed logo footprints; never infer masks in a user's browser."""
import json
import math
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def build():
    data=json.loads((ROOT/'config/planning_reference_branding.json').read_text(encoding='utf8'))
    layers=json.loads((ROOT/'config/planning_landuse_2030.json').read_text(encoding='utf8'))['layers']
    expected={x['manifest']['tile_template'] for x in layers}
    sources=data['sources']
    assert {x['template'] for x in sources}==expected and len(sources)==len(expected)
    public={}
    for source in sources:
        rings=source['rings']
        for ring in rings:
            assert len(ring)==4 and all(len(p)==2 and all(isinstance(v,(int,float)) and math.isfinite(v) for v in p) for p in ring)
            assert all(390000<p[0]<450000 and 220000<p[1]<260000 for p in ring)
        public[source['template']]=rings
    source='// Generated by scripts/build_planning_branding.py; zoom-11 world pixels.\n'
    source+="(function(root){'use strict';var marks="+json.dumps(public,ensure_ascii=False,separators=(',',':'))+';'
    source+="if(typeof module==='object'&&module.exports)module.exports=marks;if(root)root.RadarPlanningReferenceBranding=marks;})(typeof window!=='undefined'?window:null);\n"
    (ROOT/'static/js/main/planning_reference_branding.js').write_text(source,encoding='utf8')
    print(json.dumps({'sources':len(public),'logos':sum(map(len,public.values()))}))


if __name__=='__main__':
    build()
